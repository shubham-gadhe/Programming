#include<iostream>
using namespace std;

int main() 
{
    for (int i = 1; i <= 5; i++) 
    {
        cout << "Iteration number: " << i << endl;
    }
    
    return 0;
}

//////////////////////////////////////////////////////////////////
//
//  Sample Input :
//      No input required.
//
//  Sample Output :
//      Iteration number: 1
//      Iteration number: 2
//      Iteration number: 3
//      Iteration number: 4
//      Iteration number: 5
//
//////////////////////////////////////////////////////////////////